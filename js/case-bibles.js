  function getMythicSecretProfile(bibleOrScenarioId) {
    const scenId =
      typeof bibleOrScenarioId === 'string'
        ? bibleOrScenarioId
        : bibleOrScenarioId?.isMultiverse
        ? 'multiverse'
        : bibleOrScenarioId?.id || 'manor';
    return MYTHIC_SECRET_ENDINGS[scenId] || MYTHIC_SECRET_ENDINGS.manor;
  }

  function checkMythicActionTrigger(bible, actionText) {
    const profile = getMythicSecretProfile(bible);
    const clean = String(actionText || '').trim();
    if (!clean || !profile) return null;
    if (
      profile.triggerRegex.test(clean) ||
      /(النهاية السرية|السر الأسطوري|الأثر الأسطوري|افتح السر الخفي)/i.test(clean)
    ) {
      return profile;
    }
    return null;
  }

  /**
   * حسم النهاية النهائية وتوليد إحدى النهايات الخمس الحقيقية + النهاية السادسة السرية الأسطورية (★★★★★★)
   */
  function buildFinalEndingOutcome(bible, evalResult, gameStateOrReason = null) {
    const realCulprit = (bible.suspects || []).find(s => s.id === bible.culpritId);
    const realMotive = (bible.motives || []).find(m => m.id === bible.motiveId);
    const decisiveClue = (bible.clues || []).find(c => c.id === bible.decisiveClueId);

    const isGameState =
      gameStateOrReason && typeof gameStateOrReason === 'object' && !Array.isArray(gameStateOrReason);
    const gameState = isGameState ? gameStateOrReason : {};
    const dangerMaxed =
      gameStateOrReason === 'danger_maxed' ||
      (Number(gameState.dangerLevel) >= 100 && (!evalResult || !evalResult.isPerfect));

    const coverage = calculateDeductionCoverage(bible, gameState);
    const cluesFoundCount = (gameState.clues || []).length || 1;
    const totalCluesCount = (bible.clues || []).filter(c => !c.isRedHerring).length || 4;
    const culpritBroken = (gameState.suspects || []).some(
      s => s.id === bible.culpritId && s.alibiBroken
    );
    const verifiedLinksCount = (gameState.boardLinks || []).filter(l => l.verified).length;
    const mythicProfile = getMythicSecretProfile(bible);

    // شروط استحقاق النهاية السرية الأسطورية السادسة (★★★★★★):
    // إما أن اللاعب اكتشف السر الأسطوري المخبأ داخل القصة، أو حقق الاستقصاء الكامل (جميع الأدلة + كسر حجة الفاعل أو ربطان موثقان) مع اتهام صحيح
    const qualifiesForMythicEnding =
      Boolean(gameState.forceMythicSecretEnding) ||
      (evalResult &&
        (evalResult.isPerfect || evalResult.solved) &&
        (Boolean(gameState.mythicSecretUnlocked) ||
          (cluesFoundCount >= totalCluesCount && (culpritBroken || verifiedLinksCount >= 2))));

    let endingCode = 'ENDING_5_COLD_CASE';
    let endingBadge = 'ENDING 5 / 5 • COLD CASE';
    let stars = 1;
    let endingTitle = 'ملف بارد: قيدت القضية ضد مجهول';
    let summary = '';
    let isMythicSecret = false;
    let mythicReward = null;

    if (qualifiesForMythicEnding && mythicProfile) {
      endingCode = 'ENDING_6_MYTHIC_SECRET';
      endingBadge = '👑 MYTHIC SECRET ENDING • النهاية السرية الأسطورية';
      stars = 6;
      isMythicSecret = true;
      endingTitle = mythicProfile.endingTitle;
      summary = `${mythicProfile.endingSummary}\n\n🎁 المكافأة الخاصة التي ربحتها: ${mythicProfile.rewardLabel}`;
      mythicReward = {
        id: mythicProfile.id,
        relicId: mythicProfile.relicId || mythicProfile.id,
        scenarioId: mythicProfile.scenarioId,
        relicName: mythicProfile.relicName,
        relicIcon: mythicProfile.relicIcon,
        rewardLabel: mythicProfile.rewardLabel,
        rewardPerk: mythicProfile.rewardPerk || mythicProfile.rewardLabel,
        endingTitle: mythicProfile.endingTitle
      };
    } else if (evalResult && (evalResult.isPerfect || evalResult.solved)) {
      endingCode = 'ENDING_1_PERFECT';
      endingBadge = 'ENDING 1 / 5 • PERFECT VERDICT';
      stars = 5;
      endingTitle = 'العدالة الكاملة: الحقيقة الدامغة';
      summary = `أثبت أركان الجريمة الثلاثة بسلسلة أدلة مقبولة (${cluesFoundCount}/${totalCluesCount} معروضات، وتغطية استنتاج ${coverage}%)! واجهت «${realCulprit?.name}» بالمعروض الفاصل (${decisiveClue?.title}) وكشفت دافعه الحقيقي (${realMotive?.text}).`;
    } else if (dangerMaxed) {
      endingCode = 'ENDING_5_COLD_CASE';
      endingBadge = 'ENDING 5 / 5 • DANGER MAXED';
      stars = 1;
      endingTitle = 'طمس الأدلة: قيدت القضية ضد مجهول';
      summary = `بلغ مستوى الخطر 100% قبل إثبات أركان الاتهام الثلاثة! استغل الجاني الحقيقي «${realCulprit?.name}» الفوضى لإتلاف المعروض الحاسم (${decisiveClue?.title})، وأغلقت القضية لعدم كفاية الأدلة.`;
    } else if (evalResult && evalResult.culpritRight && evalResult.proofRight && !evalResult.motiveRight) {
      endingCode = 'ENDING_2_WRONG_MOTIVE';
      endingBadge = 'ENDING 2 / 5 • PARTIAL TRUTH';
      stars = 4;
      endingTitle = 'الحقيقة الناقصة: إدانة بلا دافع مكتمل';
      summary = `أصبت في تحديد الجاني «${realCulprit?.name}» وقدمت المعروض الجنائي القاطع (${decisiveClue?.title})، لكنك أخطأت في تفسير الدافع الحقيقي (${realMotive?.text}). أدين الجاني بعقوبة مخففة.`;
    } else if (evalResult && evalResult.culpritRight && !evalResult.proofRight) {
      endingCode = 'ENDING_3_WEAK_PROOF';
      endingBadge = 'ENDING 3 / 5 • INSUFFICIENT PROOF';
      stars = 3;
      endingTitle = evalResult.earlySuspicionWithoutProofChain
        ? 'شبهة مبكرة بلا سلسلة إثبات مكتملة'
        : 'ثغرة قانونية: إفلات الجاني لنقص الدليل القاطع';
      summary = evalResult.earlySuspicionWithoutProofChain
        ? `أصاب حدسك في اتهام «${realCulprit?.name}» مبكرا (تغطية استنتاج ${coverage}%)، لكنك تعجلت تقديم لائحة الاتهام قبل استكمال سلسلة المعروضات المادية وكسر حجة الغياب، فرفضت المحكمة الإدانة الكاملة!`
        : `أصاب حدسك في اتهام «${realCulprit?.name}»، لكن المعروض الذي اعتمدت عليه لم يكن الدليل الفاصل (${decisiveClue?.title}). استغل الدفاع هذه الثغرة وأطلق سراحه لعدم كفاية الإثبات!`;
    } else if (evalResult && !evalResult.culpritRight && evalResult.accusedSuspect) {
      endingCode = 'ENDING_4_WRONG_SUSPECT';
      endingBadge = 'ENDING 4 / 5 • WRONG ACCUSATION';
      stars = 2;
      endingTitle = 'مأساة العدالة: اتهام بريء وفرار الفاعل الحقيقي';
      summary = `وجهت أصابع الاتهام نحو «${evalResult.accusedSuspect.name}» بينما كان الجاني الحقيقي «${realCulprit?.name}» قد نفذ خطته بدافع (${realMotive?.text}).`;
    } else {
      summary = `استنفدت محاولات الاتهام دون الوصول إلى التركيبة الصحيحة. الحقيقة الكاملة هي أن «${realCulprit?.name}» نفذ الجريمة بدافع (${realMotive?.text}) وكان المعروض الفاصل هو (${decisiveClue?.title}).`;
    }

    const truthTimeline = (bible.timeline || []).map(t => `[${t.time}] ${t.text}`);
    const turnsTaken = gameState.turn || 1;
    const starIcons = isMythicSecret
      ? '👑👑👑👑👑👑'
      : '🟩'.repeat(Math.min(5, stars)) + '⬛'.repeat(Math.max(0, 5 - stars));

    const rampHeader = bible.weeklyRampLabel ? ` • ${bible.weeklyRampLabel}` : '';
    const shareCardText = [
      `🕵️‍♂️ قلب الغموض | ${bible.shortTitle || bible.title}${rampHeader}`,
      `${starIcons} (${endingTitle})`,
      isMythicSecret ? `🏆 الأثر الأسطوري المكتسب: ${mythicProfile.relicIcon} ${mythicProfile.relicName}` : null,
      `🔍 المعروضات المفحوصة: ${cluesFoundCount}/${totalCluesCount} • تغطية الاستنتاج: ${coverage}%`,
      `⚖️ الفصول: ${turnsTaken} • النتيجة: ${endingBadge.split('•')[0].trim()}`,
      `جرب حل القضية بنفسك بدون حرق: https://labyrinth-of-shadows.pages.dev`
    ]
      .filter(Boolean)
      .join('\n');

    return {
      endingCode,
      endingBadge,
      stars,
      isMythicSecret,
      mythicReward,
      endingTitle,
      title: endingTitle,
      summary,
      methodReveal: bible.method,
      truthTimeline,
      shareCardText
    };
  }

