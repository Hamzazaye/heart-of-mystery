  /**
   * التحقق من ربط الدليل بالمشتبه به على لوحة التحقيق
   */
  function verifyCorkboardLink(bible, clueRef, suspectRef, relationType) {
    const bibleClue = (bible.clues || []).find(
      c => c.id === clueRef || c.title === clueRef || String(c.title || '').includes(clueRef)
    );
    const suspect = (bible.suspects || []).find(
      s => s.id === suspectRef || s.name === suspectRef || String(s.name || '').includes(suspectRef)
    );
    if (!bibleClue || !suspect) {
      return {
        verified: false,
        clueId: clueRef,
        suspectId: suspectRef,
        feedback: 'تعذر التحقق من الفرضية.'
      };
    }

    if (bibleClue.isRedHerring) {
      return {
        verified: false,
        isRedHerring: true,
        clueId: bibleClue.id,
        suspectId: suspect.id,
        feedback: `مراجعة الفرضية: المعروض (${bibleClue.title}) لا يرتبط زمنيا أو جنائيا بإفادة ${suspect.name}.`
      };
    }

    const matchesContradict =
      relationType === 'contradicts' &&
      ((bibleClue.contradicts || []).includes(suspect.id) ||
        (suspect.contradictedBy || []).includes(bibleClue.id));

    const matchesSupport =
      relationType === 'supports' && (bibleClue.supports || []).includes(suspect.id);

    if (matchesContradict || matchesSupport) {
      return {
        verified: true,
        clueId: bibleClue.id,
        suspectId: suspect.id,
        feedback:
          relationType === 'contradicts'
            ? `فرضية موثقة ✓: (${bibleClue.title}) يتعارض ماديا مع إفادة ${suspect.name}!`
            : `فرضية موثقة ✓: (${bibleClue.title}) يدعم اتجاه الشبهة نحو ${suspect.name}.`
      };
    }

    return {
      verified: false,
      clueId: bibleClue.id,
      suspectId: suspect.id,
      feedback: `مراجعة الفرضية: لا يوجد تعارض مادي مباشر بين (${bibleClue.title}) وإفادة ${suspect.name}.`
    };
  }

  /**
   * التحقق الثلاثي من الاتهام (Triple Accusation Verifier + F01/F26 Proof Chain Check)
   */
  function evaluateVerdict(bible, { suspectId, motiveId, clueId }, gameState = null) {
    const culpritRight = suspectId === bible.culpritId;
    const motiveRight = motiveId === bible.motiveId;

    const chosenClue =
      (bible.clues || []).find(c => c.id === clueId || c.title === clueId) ||
      (gameState?.clues || []).find(c => c.id === clueId || c.title === clueId);

    // إذا تم تمرير gameState من داخل اللعبة، نتحقق من حيازة الدليل فعليا وسلسلة الإثبات (F01 Fix)
    const hasGameState = Boolean(gameState && Array.isArray(gameState.clues));
    const heldClueIds = hasGameState
      ? new Set((gameState.clues || []).map(c => c.id).filter(Boolean))
      : null;

    const possessesChosenClue = !hasGameState || Boolean(chosenClue && heldClueIds.has(chosenClue.id));
    const possessesDecisiveClue = !hasGameState || heldClueIds.has(bible.decisiveClueId);

    const isDecisiveOrCorroborated = Boolean(
      chosenClue &&
        possessesChosenClue &&
        (chosenClue.id === bible.decisiveClueId ||
          (!chosenClue.isRedHerring &&
            possessesDecisiveClue &&
            Array.isArray(chosenClue.supports) &&
            chosenClue.supports.includes(bible.culpritId) &&
            Array.isArray(chosenClue.contradicts) &&
            chosenClue.contradicts.includes(bible.culpritId)))
    );

    // فحص اكتمال سلسلة الإثبات الجنائي (Admissible Proof Chain):
    // لا يكفي التخمين المبكر في الفصل الأول؛ يجب حيازة الدليل الحاسم + (جمع 3 معروضات على الأقل أو كسر حجة الجاني أو توثيق رابط استنتاجي)
    let hasAdmissibleProofChain = true;
    if (hasGameState) {
      const realFoundCount = (gameState.clues || []).filter(c => !c.isRedHerring).length;
      const culpritBroken = (gameState.suspects || []).some(
        s => s.id === bible.culpritId && s.alibiBroken
      );
      const hasVerifiedLink = (gameState.boardLinks || []).some(l => l.verified);
      hasAdmissibleProofChain =
        possessesDecisiveClue && (realFoundCount >= 3 || culpritBroken || hasVerifiedLink);
    }

    const proofRight = isDecisiveOrCorroborated && hasAdmissibleProofChain;

    const correctCount =
      (culpritRight ? 1 : 0) + (motiveRight ? 1 : 0) + (proofRight ? 1 : 0);
    const isPerfect = correctCount === 3;
    const earlySuspicionWithoutProofChain =
      culpritRight && motiveRight && isDecisiveOrCorroborated && !hasAdmissibleProofChain;

    let coarseFeedback = '';
    if (isPerfect) {
      coarseFeedback = 'تطابق كامل وموثق في أركان الجريمة الثلاثة (الجاني + الدافع + الدليل القاطع)!';
    } else if (earlySuspicionWithoutProofChain) {
      coarseFeedback =
        'شبهتك نحو الجاني والدافع في محلها، لكن سلسلة الإثبات الجنائي غير مكتملة بعد! افحص المزيد من المعروضات المادية أو واجه الجاني لكسر حجته قبل إصدار الحكم الكامل.';
    } else if (!possessesChosenClue) {
      coarseFeedback =
        'لا يمكنك الاستناد إلى معروض مادي لم تفحصه وتوثقه في دفتر تحقيقك بعد!';
    } else if (correctCount === 2) {
      coarseFeedback =
        'أصبت في ركنين من أركان الاتهام وأخطأت أو نقصك الإثبات في ركن واحد فقط! راجع الدافع أو المعروض الجنائي القاطع.';
    } else if (correctCount === 1) {
      coarseFeedback =
        'أصبت في ركن واحد فقط من أركان الاتهام الثلاثة. افحص المعروضات المادية وواجه المشتبه بهم لكشف التناقض.';
    } else {
      coarseFeedback =
        'جميع أركان الاتهام الثلاثة غير مطابقة للوقائع. عاين مسرح الحدث واربط المعروضات بالمشتبه بهم.';
    }

    const realCulprit = (bible.suspects || []).find(s => s.id === bible.culpritId);
    const accusedSuspect = (bible.suspects || []).find(s => s.id === suspectId);
    const realMotive = (bible.motives || []).find(m => m.id === bible.motiveId);
    const decisiveClue = (bible.clues || []).find(c => c.id === bible.decisiveClueId);

    return {
      isPerfect,
      solved: isPerfect,
      correctCount,
      culpritRight,
      motiveRight,
      proofRight,
      possessesChosenClue,
      hasAdmissibleProofChain,
      earlySuspicionWithoutProofChain,
      coarseFeedback,
      realCulprit,
      accusedSuspect,
      realMotive,
      decisiveClue
    };
  }

