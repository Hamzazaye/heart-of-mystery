        ok: true,
        success: true,
        alibiBroken: false,
        outcomeType: 'SUPPORTS_GUILT',
        suspect,
        clue: activeClue,
        newTrust: 'تحت المساءلة',
        updatedNote: `رده حول (${activeClue.title}): «${supportReply}»`,
