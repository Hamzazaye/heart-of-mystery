  /**
   * التحقق البرمجي الصارم من سلامة ملف القضية (Case Bible Validator)
   */
  function validateCaseBible(bible) {
    if (!bible || typeof bible !== 'object') {
      return { valid: false, reason: 'ملف القضية غير موجود.' };
    }
    const suspectIds = new Set((bible.suspects || []).map(s => s.id));
    if (!suspectIds.has(bible.culpritId)) {
      return { valid: false, reason: 'الجاني المحدد غير موجود ضمن قائمة المشتبه بهم.' };
    }
    const clueMap = new Map((bible.clues || []).map(c => [c.id, c]));
    if (!clueMap.has(bible.decisiveClueId)) {
      return { valid: false, reason: 'الدليل الحاسم غير موجود في قائمة الأدلة.' };
    }

    for (const [cid, clue] of clueMap.entries()) {
      const visited = new Set([cid]);
      const queue = [...(clue.needs || [])];
      while (queue.length > 0) {
        const dep = queue.shift();
        if (visited.has(dep)) {
          return { valid: false, reason: `اعتماد دائري في الأدلة عند ${cid}` };
        }
        visited.add(dep);
        const depObj = clueMap.get(dep);
        if (depObj && Array.isArray(depObj.needs)) {
          queue.push(...depObj.needs);
        }
      }
    }

    return { valid: true };
  }

  /**
   * الحصول على نسخة عميقة ومقفلة (Frozen Copy) من ملف القضية
   * يدعم توليد حقيقة متجددة في كل جولة لعب (Dynamic Playthrough Truth) ثم قفلها طوال الجولة
   */
  function getLockedCaseBible(scenarioId, customPrompt = '', playerName = 'آدم', options = {}) {
    if (scenarioId === 'multiverse' && window.MysteryMultiverseEngine?.buildMultiverseCaseBible) {
      return window.MysteryMultiverseEngine.buildMultiverseCaseBible(playerName, options);
    }
    const raw =
      scenarioId === 'custom'
        ? buildCustomCaseBible(customPrompt, playerName)
        : CASE_BIBLES[scenarioId] || CASE_BIBLES.manor;
    const copy = JSON.parse(JSON.stringify(raw));

    const shouldRandomize =
      options.randomizeTruth !== false &&
      scenarioId !== 'daily' &&
      Array.isArray(copy.suspects) &&
      copy.suspects.length >= 3 &&
      Array.isArray(copy.motives) &&
      copy.motives.length >= 3;

    if (shouldRandomize) {
      const pickedSuspect = copy.suspects[Math.floor(Math.random() * copy.suspects.length)];
      const pickedMotive = copy.motives[Math.floor(Math.random() * copy.motives.length)];
      copy.culpritId = pickedSuspect.id;
      copy.motiveId = pickedMotive.id;

      const decisive = (copy.clues || []).find(c => c.id === copy.decisiveClueId);
      if (decisive) {
        decisive.supports = [pickedSuspect.id];
        decisive.contradicts = [pickedSuspect.id];
      }
      if (!Array.isArray(pickedSuspect.contradictedBy)) {
        pickedSuspect.contradictedBy = [];
      }
      if (!pickedSuspect.contradictedBy.includes(copy.decisiveClueId)) {
        pickedSuspect.contradictedBy.push(copy.decisiveClueId);
      }
      const decisiveBreakText = `حسنا، لا مفر من الإنكار أمام هذا الدليل القاطع (${
        decisive ? decisive.title : 'الدليل الجنائي'
      })! نعم... أنا من دبر الأمر بدافع (${pickedMotive.text})، وظننت أن حجة غيابي لن يكشفها أحد!`;
      pickedSuspect.confessionOnBreak = decisiveBreakText;
      if (!pickedSuspect.responsesByClue) pickedSuspect.responsesByClue = {};
      pickedSuspect.responsesByClue[copy.decisiveClueId] = decisiveBreakText;
    }

    const culprit = (copy.suspects || []).find(s => s.id === copy.culpritId);
    const motive = (copy.motives || []).find(m => m.id === copy.motiveId);
    const decisive = (copy.clues || []).find(c => c.id === copy.decisiveClueId);
    copy.summaryBlueprint = `الجاني الحقيقي الثابت في هذه الجولة: ${
      culprit ? culprit.name : copy.culpritId
    } | الدافع الحقيقي: ${motive ? motive.text : copy.motiveId} | الدليل القاطع: ${
      decisive ? decisive.title : copy.decisiveClueId
    } | طريقة الجريمة: ${copy.method}`;
    const check = validateCaseBible(copy);
    if (!check.valid) {
      console.warn('Case Bible validation warning:', check.reason);
    }
    return copy;
  }

  /**
   * حساب نسبة الاستنتاج الفعلي (Real Deduction Coverage Meter)
   */
  function calculateDeductionCoverage(bible, gameState) {
    if (!bible || !gameState) return 15;
    const realClues = (bible.clues || []).filter(c => !c.isRedHerring);
    const totalCluesCount = Math.max(1, realClues.length);
    const foundRealClues = (gameState.clues || []).filter(gc =>
      realClues.some(
        rc =>
          rc.id === gc.id ||
          rc.title === gc.title ||
          String(gc.title || '').includes(rc.title) ||
          String(rc.title || '').includes(gc.title)
      )
    ).length;

    const brokenAlibis = (gameState.suspects || []).filter(s => s.alibiBroken).length;
    const totalSuspects = Math.max(1, (bible.suspects || []).length);

    const verifiedLinks = (gameState.boardLinks || []).filter(l => l.verified).length;

    const clueScore = (foundRealClues / totalCluesCount) * 55;
    const alibiScore = (brokenAlibis / totalSuspects) * 30;
    const linkScore = Math.min(15, verifiedLinks * 5);

    return Math.min(100, Math.max(12, Math.round(clueScore + alibiScore + linkScore)));
  }

