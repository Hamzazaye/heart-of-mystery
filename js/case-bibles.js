  /**
   * استخراج أسماء الشخصيات والآلية المادية من نص القضية المخصصة (F11 & F29 Fix)
   */
  function extractCustomConstraints(rawPrompt) {
    const clean = String(rawPrompt || '').trim();
    const extractedNames = [];

    // 1. استخراج الأسماء المسبوقة بألقاب أو المفصولة بشرطة مائلة أو فاصلة
    const slashMatch = clean.match(/([أ-ي]{3,12})\s*[\/،,-]\s*([أ-ي]{3,12})\s*[\/،,-]\s*([أ-ي]{3,12})/);
    if (slashMatch) {
      extractedNames.push(slashMatch[1], slashMatch[2], slashMatch[3]);
    } else {
      const knownNamesPool = [
        'هلا', 'سامر', 'يزن', 'نديم', 'سلمى', 'راشد', 'سارة', 'طارق', 'ليلى', 'فريد',
        'عمران', 'مازن', 'رنا', 'سليم', 'سنان', 'ياقوت', 'جسار', 'فؤاد', 'نادر', 'ريم',
        'منصور', 'يونس', 'كمال', 'زياد', 'بهزاد', 'فيروز', 'ريحان', 'خالد', 'مريم', 'زيد'
      ];
      for (const candidate of knownNamesPool) {
        if (clean.includes(candidate) && !extractedNames.includes(candidate)) {
          extractedNames.push(candidate);
        }
      }
    }

    const s1Name = extractedNames[0] || 'سامر الكيلاني';
    const s2Name = extractedNames[1] || 'هلا الراوي';
    const s3Name = extractedNames[2] || 'يزن المنذر';

    let mechanismLabel = 'جدول التشغيل والقفل الزمني';
    if (/كهرباء|تيار|قاطع|مولد/.test(clean)) {
      mechanismLabel = 'جدول انقطاع الكهرباء والقاطع الفرعي';
    } else if (/مرصد|تلسكوب|فلك|كسوف/.test(clean)) {
      mechanismLabel = 'زاوية التلسكوب وسجل الرصد الفلكي';
    } else if (/سم|قهوة|شاي|عقار|دواء/.test(clean)) {
      mechanismLabel = 'الأثر الكيميائي في القارورة الزجاجية';
    } else if (/أرض مجهولة|صحراء|واحة|بوصلة|إسطرلاب/.test(clean)) {
      mechanismLabel = 'إبرة البوصلة المنحرفة وخريطة القافلة';
    }

    return {
      s1Name,
      s2Name,
      s3Name,
      mechanismLabel,
      suspects: [s1Name, s2Name, s3Name],
      mechanism: mechanismLabel
    };
  }

